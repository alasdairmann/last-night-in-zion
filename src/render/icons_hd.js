// Pixel toolkit for one 24x24 canvas context.
export function hdKit(ctx) {
  const P = (x, y, c) => { if (c === '#00000000') { ctx.clearRect(x, y, 1, 1); return; } ctx.fillStyle = c; ctx.fillRect(x, y, 1, 1); }; // '#00000000' erases
  const R = (x, y, w, h, c) => { if (c === '#00000000') { ctx.clearRect(x, y, w, h); return; } ctx.fillStyle = c; ctx.fillRect(x, y, w, h); };
  const disc = (cx, cy, r, ramp) => {
    const [hi, mid, lo] = Array.isArray(ramp) ? ramp : [ramp, ramp, ramp];
    for (let y = Math.floor(cy - r - 1); y <= cy + r; y++) for (let x = Math.floor(cx - r - 1); x <= cx + r; x++) {
      const dx = x + 0.5 - cx, dy = y + 0.5 - cy; if (dx * dx + dy * dy > r * r) continue;
      const t = (dx + dy) / r; P(x, y, t < -0.55 ? hi : t > 0.75 ? lo : mid);
    }
  };
  const ring = (cx, cy, r0, r1, ramp) => {
    const [hi, mid, lo] = ramp;
    for (let y = Math.floor(cy - r1 - 1); y <= cy + r1; y++) for (let x = Math.floor(cx - r1 - 1); x <= cx + r1; x++) {
      const dx = x + 0.5 - cx, dy = y + 0.5 - cy, d = Math.hypot(dx, dy); if (d > r1 || d < r0) continue;
      const t = (dx + dy) / d; P(x, y, t < -0.7 ? hi : t > 0.7 ? lo : mid);
    }
  };
  const line = (x0, y0, x1, y1, c, t = 1) => {
    const n = Math.max(1, Math.ceil(Math.hypot(x1 - x0, y1 - y0) * 2));
    for (let i = 0; i <= n; i++) { const x = x0 + (x1 - x0) * i / n, y = y0 + (y1 - y0) * i / n; if (t <= 1) P(Math.floor(x), Math.floor(y), c); else R(Math.round(x - t / 2), Math.round(y - t / 2), Math.round(t), Math.round(t), c); }
  };
  const poly = (pts, c) => {
    for (let y = 0; y < 24; y++) for (let x = 0; x < 24; x++) {
      const px = x + 0.5, py = y + 0.5; let inside = false;
      for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
        const [xi, yi] = pts[i], [xj, yj] = pts[j];
        if ((yi > py) !== (yj > py) && px < (xj - xi) * (py - yi) / (yj - yi) + xi) inside = !inside;
      }
      if (inside) P(x, y, c);
    }
  };
  return { P, R, disc, ring, line, poly };
}

